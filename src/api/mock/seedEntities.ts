const createDefaultApprovals = (customStatus?: Partial<Record<ApprovalStep, { decision: 'APPROVED' | 'PENDING' | 'REJECTED' | 'SENT_BACK'; approverId?: string; remarks?: string }>>): ApprovalStepState[] => {
  const steps: ApprovalStep[] = [
    'QUOTATION_UPDATE',
    'NEGOTIATION',
    'SPECIAL_APPROVAL',
    'CLIENT_CONFIRMATION',
    'PROJECT_KICKOFF',
    'EXECUTION',
    'CLOSURE_BILLING',
  ];

  return steps.map((step) => {
    const custom = customStatus?.[step];
    return {
      step,
      approverId: custom?.approverId || null,
      approverName: custom?.approverId ? 'Manager / Approver' : null,
      decision: custom?.decision || 'PENDING',
      remarks: custom?.remarks || null,
      decidedAt: custom?.decision && custom.decision !== 'PENDING' ? '2026-09-10T10:00:00Z' : null,
      pendingSince: custom?.decision === 'PENDING' ? '2026-09-08T09:00:00Z' : null,
    };
  });
};

